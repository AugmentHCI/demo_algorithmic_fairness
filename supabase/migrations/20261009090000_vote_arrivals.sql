-- Votes come from shared tablets and buttons, so they carry no identity. Each
-- phone reports when its participant reaches a round's vote screen; the
-- results screens show every vote as the persona of someone who arrived around
-- the time it was cast (the matching happens in the app, `domain/voters.ts`).

create table if not exists public.vote_arrivals (
	id bigint generated always as identity primary key,
	created_at timestamptz not null default now(),
	event_id text not null default 'default' check (char_length(event_id) between 1 and 64),
	rule text not null check (rule in ('bare_box', 'counterfactual', 'parity', 'opportunity')),
	-- Generated by the phone and kept for the participant's whole journey.
	participant_id uuid not null,
	persona_id text not null check (char_length(persona_id) <= 16),
	colour_id text not null check (colour_id in ('yellow', 'green', 'blue', 'red')),
	-- A participant arrives once per round, also when they step back and forth.
	constraint vote_arrivals_participant_rule_key unique (event_id, rule, participant_id)
);

create index if not exists vote_arrivals_event_rule_idx
	on public.vote_arrivals (event_id, rule, created_at);

alter table public.vote_arrivals enable row level security;

-- The votes are now read row by row (in the order cast) to pair them with arrivals.
create index if not exists votes_event_rule_created_idx
	on public.votes (event_id, rule, created_at);
